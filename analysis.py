'''
[역할]  너는 파이썬 데이터 처리를 돕는 조교다.
[목표]  아래 명세대로 CSV를 정제하는 함수 정제(df)를 만들어라.
[데이터]
  파일: scores_2026.csv, 114행 5열 (학번 이름 반 과목 점수)
  점수는 0 이상 100 이하의 정수여야 한다.
  반과 과목 값의 앞뒤에 공백이 섞여 있다.
[처리 규칙]  ← 명세서 ③④⑤ 칸 + 데이터 특성을 옮깁니다
  1) 점수가 비어 있는 행은 삭제한다.
  2) 모든 열이 완전히 같은 행은 하나만 남긴다.
  3) 반과 과목의 앞뒤 공백을 제거한다.
  4) 점수가 0~100 밖인 행은 삭제한다.
[제약]  pandas만 사용. 각 단계 뒤 남은 행 수를 print 할 것.
'''
from turtle import pd

def 정제(df):
    # 1. 점수가 비어 있는 행 삭제
    df = df.dropna(subset=["점수"])
    print("1단계 - 점수 결측치 삭제:", len(df), "행")

    # 2. 모든 열이 완전히 같은 중복 행 제거
    df = df.drop_duplicates()
    print("2단계 - 중복 행 제거:", len(df), "행")

    # 3. 반과 과목의 앞뒤 공백 제거
    df["반"] = df["반"].str.strip()
    df["과목"] = df["과목"].str.strip()
    print("3단계 - 공백 제거:", len(df), "행")

    # 4. 점수가 0~100 범위를 벗어난 행 삭제
    df["점수"] = pd.to_numeric(df["점수"], errors="coerce")
    df = df[df["점수"].between(0, 100)]
    print("4단계 - 점수 범위 확인:", len(df), "행")
    return df

'''
정제된 df 에서 과목이 '수학'인 행만 남기는 코드를 한 줄로 써라.
그리고 남은 행 수를 print 하라.
'''
df = df[df["과목"] == "수학"]
print("과목이 '수학'인 행 수:", len(df))
